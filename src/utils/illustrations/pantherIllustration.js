const TONE_STYLE = { a: ';fill:var(--il-a)', b: ';fill:var(--il-b)' }
let order = 0
const PARTS = { 1: [' ear', ';--e:0s'], 2: [' ear', ';--e:-3s'], 8: [' lid', ''], 9: [' lid', ''] }
const fills = SHAPES.map(([tone, points], index) => {
  const [part, partStyle] = PARTS[index] || ['', '']
  const cls = (TONE_STYLE[tone] ? 'f t' : `f ${tone}`) + part
  const extra = (TONE_STYLE[tone] || '') + partStyle
  return `<path class="${cls}" pathLength="1" style="--i:${order++}${extra}" d="${smooth(points, true)}"/>`
})
const strokes = LINES.map(points => `<path class="st" pathLength="1" style="--i:${order++}" d="${smooth(points, false)}"/>`)

export const panther = fills.join('') + strokes.join('')
