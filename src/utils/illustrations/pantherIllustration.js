const SCALE = 0.158
const CENTER = [414, 474]
const OFFSET_Y = -5

const place = ([x, y]) => [(x - CENTER[0]) * SCALE, (y - CENTER[1]) * SCALE + OFFSET_Y]
const fmt = value => +value.toFixed(1)
const mirror = points => points.map(([x, y]) => [850 - x, y]).reverse()

// Catmull-Rom points to cubic Bezier segments
function smooth(points, isClosed) {
  const pts = points.map(place)
  const count = pts.length
  const at = index => (isClosed ? pts[(index + count) % count] : pts[Math.min(Math.max(index, 0), count - 1)])
  const last = isClosed ? count : count - 1
  let d = `M${fmt(pts[0][0])} ${fmt(pts[0][1])}`
  for (let i = 0; i < last; i++) {
    const [p0, p1, p2, p3] = [at(i - 1), at(i), at(i + 1), at(i + 2)]
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6]
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6]
    d += `C${fmt(c1[0])} ${fmt(c1[1])} ${fmt(c2[0])} ${fmt(c2[1])} ${fmt(p2[0])} ${fmt(p2[1])}`
  }
  return isClosed ? `${d}Z` : d
}

